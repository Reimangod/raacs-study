"""Independent small-register exterior-product audit of actual NOCI outputs.

This is evaluation-only; the production constructor never sees these vectors,
the old sparse Fock Hamiltonian, or an FCI reference. No raw acquisition is
generated by this auditor. It is not a many-qubit scalable audit route.
"""
from __future__ import annotations
import argparse
from itertools import combinations
import json
from pathlib import Path
import sqlite3
from time import perf_counter
import numpy as np
from scipy.linalg import eigh,svd
from qiskit import qpy
from qiskit.quantum_info import Statevector
from io import BytesIO
from .common import ROOT,file_digest,save_json
from .chemistry import load_reference
from .nonorthogonal_ci import occupied_columns
from .multibasis_study import unpack,valid
from .ansatz import measurement_equivalent_circuit,resources


def exterior_vector(columns):
    n,ne=columns.shape
    if n>16:raise ValueError('Evaluation-only exterior audit capped at16qubits')
    out=np.zeros(1<<n,complex)
    for occ in combinations(range(n),ne):
        idx=sum(1<<(n-1-q) for q in occ);out[idx]=np.linalg.det(columns[list(occ)])
    return out


def audit(root):
    root=Path(root);cfg=json.loads((root/'manifest.json').read_text());start=perf_counter()
    for name,sha in cfg['implementation'].items():
        if file_digest(ROOT/'benchmark'/name)!=sha:raise RuntimeError('Frozen implementation changed: '+name)
    if file_digest(ROOT/'study-v1/MULTIBASIS_NOCI_V1.md')!=cfg['spec_sha256']:raise RuntimeError('Frozen spec changed')
    db=sqlite3.connect(f"file:{root/'events.sqlite'}?mode=ro",uri=True)
    expected=len(cfg['cases'])*len(cfg['methods'])*len(cfg['arms'])*len(cfg['M'])*len(cfg['seeds'])
    statuses=dict(db.execute('SELECT status,count(*) FROM tasks GROUP BY status').fetchall())
    available=sum(statuses.values())==expected and not any(x not in ('COMPLETED','MISSING_SOURCE_METHOD') for x in statuses)
    matrix_checks=0;state_checks=0;raw_shots=0;classical_samples=0;maxenergy=0.;maxmatrix=0.;maxrotation=0.;zero_overlaps=0
    cost_corrections=[]
    for case,basis_blob in db.execute('SELECT case_id,payload FROM bases ORDER BY case_id').fetchall():
        basis=unpack(basis_blob);rotations=[np.asarray(u) for u in basis['rotations']];info=basis['problem']
        ref=load_reference(Path(cfg['source'])/'references'/case)
        vectors={}
        def vector(node):
            node=tuple(node)
            if node not in vectors:vectors[node]=exterior_vector(occupied_columns(rotations[node[0]],node[1]))
            return vectors[node]
        for method,b,raw,meta_blob in db.execute('SELECT method,basis,qpy,payload FROM circuits WHERE case_id=?',(case,)).fetchall():
            meta=unpack(meta_blob);qc=qpy.load(BytesIO(bytes(raw)))[0]
            if qc.num_qubits>8 and cfg['mode']=='quick':raise ValueError('Quick scope unexpectedly enlarged')
            original=meta['origin']
            # Bind the original full preparation using its preserved path/event
            # loader, independently of the appended measurement rotation.
            from .multibasis_primitives import source_preparation
            prep,_=source_preparation(case,method);source=Statevector.from_instruction(prep).data
            expected_state=np.zeros_like(source)
            for idx in np.flatnonzero(abs(source)>1e-14):
                col=occupied_columns(rotations[b].conj().T,int(idx))
                expected_state+=source[idx]*exterior_vector(col)
            actual=Statevector.from_instruction(qc).data
            error=float(np.max(abs(expected_state-actual)));maxrotation=max(maxrotation,error)
            if error>1e-9:raise RuntimeError('Physical orbital measurement direction/fermionic phase')
            sample,_=measurement_equivalent_circuit(qc)
            if np.max(abs(abs(Statevector.from_instruction(sample).data)**2-abs(actual)**2))>1e-9:raise RuntimeError('Z-only postrotation compiler')
            rr=resources(sample,0,0)
            if any(rr[k]!=meta['resources'][k] for k in ('cnot_count','cnot_depth','total_depth')):raise RuntimeError('Resource reconstruction')
            # The original helper's 0 parameter/operator arguments are sentinels,
            # NOT independent ansatz counts. Correct the *interpretation* by an
            # additive cost view without altering the frozen circuit record.
            cost_corrections.append({'case_id':case,'method':method,'basis':b,
                'combined_n_independent_ansatz_parameters':None,'combined_selected_operator_count':None,
                'placeholder_helper_fields_not_scientific_counts':['resources.parameter_count','resources.selected_operator_count'],
                'basis_optimized_variables_per_stage':basis['construction']['orbital_parameters_per_nonidentity_basis'],
                'source_result':original['source_result'],'actual_CNOT':rr['cnot_count'],'actual_CNOT_depth':rr['cnot_depth']})
            state_checks+=1
        for payload, in db.execute("SELECT d.payload FROM draws d JOIN acquisitions a ON a.id=d.acquisition WHERE a.case_id=? AND d.status='COMPLETED'",(case,)).fetchall():
            draw=unpack(payload)
            if sum(draw['counts'])!=draw['actual_raw'] or draw['actual_raw']!=draw['requested']:raise RuntimeError('Raw draw accounting')
            if len(draw['ids'])!=len(set(draw['ids'])) or any(c<=0 for c in draw['counts']):raise RuntimeError('Count multiplicity')
            if sum(c for i,c in zip(draw['ids'],draw['counts']) if valid(i,info))!=draw['valid_sector_raw']:raise RuntimeError('Sector accounting')
            raw_shots+=draw['metadata']['raw_simulated_quantum_shots'];classical_samples+=draw['metadata']['classical_uniform_samples']
        tasks=db.execute("SELECT id,payload FROM tasks WHERE case_id=? AND status='COMPLETED'",(case,)).fetchall()
        for tid,taskblob in tasks:
            task=unpack(taskblob)
            if db.execute('SELECT status FROM acquisitions WHERE id=?',(task['acquisition_id'],)).fetchone()!=('COMPLETED',):raise RuntimeError('Task/acquisition binding')
            rows=db.execute('SELECT R,payload FROM readouts WHERE task=? ORDER BY R',(tid,)).fetchall()
            if [x[0] for x in rows]!=cfg['R']:raise RuntimeError('Incomplete R readouts')
            for R,payload in rows:
                result=unpack(payload);nodes=result['selected_nodes']
                if len(nodes)>R or len({tuple(x) for x in nodes})!=len(nodes):raise RuntimeError('Basis-tagged vector cap/dedup')
                v=np.column_stack([vector(x) for x in nodes]);s=v.conj().T@v;h=v.conj().T@(ref['h']@v)
                # Independent physical-space SVD, rather than production's
                # eigenvectors of S, obtains the retained span and its energy.
                u,singular,_=svd(v,full_matrices=False)
                keep=singular**2>cfg['rank_relative_cutoff']*singular[0]**2
                q=u[:,keep];hp=q.conj().T@(ref['h']@q);ev=eigh((hp+hp.conj().T)/2,eigvals_only=True)
                err=abs(float(ev[0])-result['energy_Ha']);maxenergy=max(maxenergy,err)
                if err>1e-7 or int(keep.sum())!=result['rank']:raise RuntimeError('Independent NOCI energy/rank')
                # Overlap eigenvalues are independent exterior contractions.
                err=float(np.max(abs(eigh(s,eigvals_only=True)-result['overlap_eigenvalues'])))
                maxmatrix=max(maxmatrix,err)
                if err>1e-8:raise RuntimeError('Independent overlap spectrum')
                if result['energy_Ha']<ref['meta']['fci_energy']-1e-7:raise RuntimeError('Evaluation-only variational check')
                zero_overlaps+=int(np.count_nonzero(abs(s)<1e-12));matrix_checks+=1
    db.close()
    record={'status':'ALL_QUICK_SPACES_INDEPENDENTLY_VALIDATED' if available and cfg['mode']=='quick' else 'PARTIAL_OR_PREFLIGHT_ONLY',
            'planned_tasks':expected,'tasks_by_status':statuses,'independent_exterior_projected_spaces':matrix_checks,
            'physical_rotated_circuit_checks':state_checks,'max_energy_error_Ha':maxenergy if matrix_checks else None,
            'max_overlap_spectrum_error':maxmatrix if matrix_checks else None,
            'max_rotation_state_amplitude_error':maxrotation if state_checks else None,'zero_overlap_entries_checked':zero_overlaps,
            'unique_committed_new_model_shots':raw_shots,'unique_classical_uniform_samples':classical_samples,
            'new_quantum_acquisitions_in_auditor':0,'hardware_shots':0,'FCI_scope':'post-hoc variational evaluation only',
            'database_sha256':file_digest(root/'events.sqlite'),'audit_wall_seconds':perf_counter()-start,
            'audit_code_sha256':file_digest(__file__),'parameter_cost_view':'parameter-cost-interpretation-v1.json',
            'whole_goal_complete':False}
    save_json(root/'parameter-cost-interpretation-v1.json',{'status':'ADDITIVE_INTERPRETATION_NO_SOURCE_CHANGE','rows':cost_corrections})
    save_json(root/('validation.json' if available and cfg['mode']=='quick' else 'partial-validation-v2.json'),record)
    return record


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--output',default=str(ROOT/'results/multibasis-NOCI-quick-v1'))
    print(json.dumps(audit(p.parse_args().output)))
